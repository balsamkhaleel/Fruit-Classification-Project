import tensorflow as tf
import numpy as np
import cv2
import os
import matplotlib.pyplot as plt

# -----------------------------
# 1) Load the trained model
# -----------------------------
model = tf.keras.models.load_model("/content/vgg16_fruit_transfer.h5")
print("The VGG16 model loaded successfully")

# -----------------------------
# 2) Load class names from Train folder
# -----------------------------
train_dir = "/content/my_drive/MyDrive/processed_data_split/Train"

temp = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    image_size=(224,224),
    batch_size=32,
    shuffle=False,
)

class_names = temp.class_names
print("Classes found:", class_names)

# -----------------------------
# 3) Test directory
# -----------------------------
test_dir = "/content/my_drive/MyDrive/processed_data_split/Test"

total_images = 0
correct_predictions = 0

# -----------------------------
# 4) Loop over each class folder
# -----------------------------
for class_folder in os.listdir(test_dir):

    class_path = os.path.join(test_dir, class_folder)

    if not os.path.isdir(class_path):
        continue

    print(f"\n--- Testing class: {class_folder} ---")

    for img_name in os.listdir(class_path):

        img_path = os.path.join(class_path, img_name)

        if not img_name.lower().endswith((".jpg", ".jpeg", ".png", ".bmp")):
            continue

        img = cv2.imread(img_path)
        if img is None:
            print("Failed to read:", img_path)
            continue

        # Preprocess image
        resized_img = cv2.resize(img, (224,224))
        resized_img = resized_img.astype("float32") / 255.0
        resized_img = np.expand_dims(resized_img, axis=0)

        # Prediction
        pred = model.predict(resized_img, verbose=0)
        class_id = np.argmax(pred)
        confidence = np.max(pred)
        predicted_class = class_names[class_id]

        total_images += 1
        if predicted_class == class_folder:
            correct_predictions += 1

        print(f"{img_name}  -->  Predicted: {predicted_class}  |  Confidence: {confidence:.4f}")

# -----------------------------
# 5) Final Accuracy on Test Set
# -----------------------------
accuracy = correct_predictions / total_images * 100
print("\n==============================")
print(f"Total Test Images: {total_images}")
print(f"Correct Predictions: {correct_predictions}")
print(f"Test Accuracy: {accuracy:.2f}%")
print("==============================")

# -----------------------------
# 6) Plot Accuracy (Bar Chart)
# -----------------------------
plt.figure(figsize=(6,5))
plt.bar(["Test Accuracy"], [accuracy])
plt.ylim(0, 100)
plt.ylabel("Accuracy (%)")
plt.title("Model Accuracy on Test Dataset")
plt.text(0, accuracy + 2, f"{accuracy:.2f}%", ha='center', fontsize=12)
plt.show()

