def clean_name(name):
    base = name.split('.')[0]
    cleaned = "".join([c for c in base if c.isalnum()])
    return cleaned

def remove_duplicates(files):
    unique = []
    duplicates = []

    for f in files:
        cleaned = clean_name(f)
        if cleaned not in unique:
            unique.append(cleaned)
        else:
            duplicates.append(f)

    return duplicates

def apply_clahe_lab(img):
    lab = cv2.cvtColor(img, cv2.COLOR_BGR2LAB)
    L, A, B = cv2.split(lab)
    A = (A * 0.9).astype("uint8")
    B = (B * 0.9).astype("uint8")
    clahe = cv2.createCLAHE(clipLimit=1.5, tileGridSize=(8, 8))
    L_eq = clahe.apply(L)
    lab_eq = cv2.merge((L_eq, A, B))
    result = cv2.cvtColor(lab_eq, cv2.COLOR_LAB2BGR)
    return result

def denoise(img):
    return cv2.fastNlMeansDenoisingColored(img, None, 10, 10, 7, 11)

def resize_image(img, size=(223, 223)):
    return cv2.resize(img, size)

def normalize(img):
    norm = img.astype("float32") / 255.0
    norm = (norm * 255).astype("uint8")
    return norm

total_deleted = 0

for root, dirs, files in os.walk(input_path):

    duplicates = remove_duplicates(files)
    if duplicates:
        print(f"Duplicates removed in folder '{root}': {len(duplicates)}")
        total_deleted += len(duplicates)
        for d in duplicates:
            files.remove(d)

    for filename in files:
        if filename.lower().endswith((".jpg", ".jpeg", ".png", ".bmp")):
            img_path = os.path.join(root, filename)
            img = cv2.imread(img_path)

            if img is None:
                print("Failed to read image:", img_path)
                continue

            relative_path = os.path.relpath(root, input_path)
            save_dir = os.path.join(output_path, relative_path)
            os.makedirs(save_dir, exist_ok=True)

            img = apply_clahe_lab(img)
            img = denoise(img)
            img = resize_image(img)
            img = normalize(img)

            save_path = os.path.join(save_dir, filename)
            cv2.imwrite(save_path, img)

print(f"\nProcessing completed successfully!")
print(f"Total duplicates deleted: {total_deleted}")

import os
import shutil
import random

# ----- إعداد المسارات -----
