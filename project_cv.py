output_path = "/content/my_drive/MyDrive/processed_data_split"  # المجلد الجديد للتقسيم
train_ratio = 0.8
test_ratio = 0.2

# إنشاء مجلدات Train و Test
train_path = os.path.join(output_path, "Train")
test_path = os.path.join(output_path, "Test")
os.makedirs(train_path, exist_ok=True)
os.makedirs(test_path, exist_ok=True)

# ----- تقسيم الصور -----
for category in os.listdir(input_path):
    category_path = os.path.join(input_path, category)
    if not os.path.isdir(category_path):
        continue

    # إنشاء مجلدات الفئة داخل Train و Test
    os.makedirs(os.path.join(train_path, category), exist_ok=True)
    os.makedirs(os.path.join(test_path, category), exist_ok=True)

    images = [f for f in os.listdir(category_path) if f.lower().endswith((".jpg", ".jpeg", ".png", ".bmp"))]
    random.shuffle(images)

    split_index = int(len(images) * train_ratio)
    train_images = images[:split_index]
    test_images = images[split_index:]

    # نسخ الصور
    for img_name in train_images:
        src = os.path.join(category_path, img_name)
        dst = os.path.join(train_path, category, img_name)
        shutil.copy2(src, dst)

    for img_name in test_images:
        src = os.path.join(category_path, img_name)
        dst = os.path.join(test_path, category, img_name)
        shutil.copy2(src, dst)

    print(f"{category}: {len(train_images)} train, {len(test_images)} test")

